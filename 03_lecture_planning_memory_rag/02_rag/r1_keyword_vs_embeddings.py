"""Практика R1 — пошук по словах проти пошуку по змісту, на одному корпусі.

У демо памʼяті `/search` шукав по словах і промахнувся: в архіві написано
«таймзонами», користувач спитав «таймзони». Беремо ті самі нотатки й той
самий промах — і додаємо поруч пошук по векторах.

Третя сцена показує зворотний бік: ембединги не розуміють заперечення.
Близькість — це не правильність.

Запуск:  python r1_keyword_vs_embeddings.py
"""
from corpus import search_keyword, search_semantic


def compare(tag: str, query: str) -> None:
    print(f"\n[{tag}] запит: {query!r}")
    hits = search_keyword(query)
    print(f"  keyword : {[d['id'] for d in hits] or 'нічого не знайдено'}")
    print("  semantic:", "  ".join(f"{d['id']}={s:.3f}" for s, d in search_semantic(query)))


if __name__ == "__main__":
    # 1. Словоформа. Той самий промах, що й у `/search` демо памʼяті.
    compare("СЛОВОФОРМА", "таймзони")
    print("  -> у нотатці «таймзонами», у запиті «таймзони»: для словника це різні слова")

    # 2. Синоніми: із d1 запит не ділить ЖОДНОГО значущого слова.
    compare("СИНОНІМИ", "як не починати все спочатку, якщо процес упав посеред задачі")
    print("  -> у d1 немає слів «процес», «упав», «спочатку» — а знайшовся саме він")

    # 3. Пастка. Два протилежні запити -> та сама пара документів.
    compare("ПАСТКА", "чим запускати тести")
    compare("ПАСТКА", "чим НЕ запускати тести")
    print("  -> «НЕ» перевернуло питання, але не перевернуло видачу: d3 і d4")
    print("     тримаються поруч в обох випадках. Вектор кодує тему, а не заперечення.")
    print("\n[ВИСНОВОК] близькість != правильність: ембединги дістають з архіву те,")
    print("           що поруч по змісту, а відповідати за зміст має LLM (див. r2).")

