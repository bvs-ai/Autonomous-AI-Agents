"""КРОК 3b (Google ADK). Той самий маршрут, але обирає його модель.

На кроці 3 маршрут вирішував код: функція `check_policy` читала суму й ліміт
і виставляла `ctx.route`. Тут ми прибираємо граф зовсім і кажемо те саме
правило **словами в інструкції**. Далі модель сама вирішує, кому передати
роботу — і за це рішення ми платимо окремим викликом LLM.

Механізм ADK називається **передача управління** (agent transfer). Достатньо
покласти агентів у `sub_agents`, і фреймворк сам додає моделі інструмент
`transfer_to_agent(agent_name)`. У виводі ви побачите його виклик буквально —
рядок `[support_router] викликає transfer_to_agent`, після якого зміниться
автор подій. Це і є момент передачі.

Три речі, заради яких цей файл існує:

* саме тут вперше працює `description` агента з кроку 1. Модель обирає ціль
  не за іменем, а за описом — інших відомостей про колег у неї немає;
* межі свободи все одно задає код: список `sub_agents` і прапорці
  `disallow_transfer_to_parent` / `disallow_transfer_to_peers`. Модель обирає
  всередині множини, яку дозволили ми;
* правило регламенту живе в промпті, тобто його можна порушити. Запустіть
  кілька разів — рано чи пізно побачите не ту гілку. У графі з кроку 3 таке
  неможливе за побудовою.

Перед банером ADK друкує попередження про `context_cache_config` — не глушимо
його навмисно: воно про ціну цього механізму. Кожна передача міняє системну
інструкцію і набір інструментів, тобто префікс промпту, тож кеш попереднього
агента не працює і промпт їде до моделі повністю заново.

Ще одна відмінність від кроків 2-3, менш помітна, але важлива: після передачі
колега бачить **історію розмови**, а не іменовану комірку `session.state`.
Тому `refund_operator` тут описаний заново, без підстановки `{investigation}`.
Механізм передачі даних змінився разом із механізмом маршруту.

Запуск:  .venv/bin/python 03_adk/g3b_transfer.py
         .venv/bin/python 03_adk/g3b_transfer.py --limit 10   # гілка «до людини»
"""
import argparse
import asyncio
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from g1_agent import run, support_agent
from google.adk.agents import LlmAgent

from common import MODEL, REFUND_LIMIT_USD, TICKET, Metrics, banner, refund

# ── Колеги, між якими обиратиме модель ──────────────────────────────────────
# `description` тут не для людей: саме його модель читає, коли вирішує, кому
# передати роботу. Порівняйте з `instruction` — її читає сам агент.
refund_agent = LlmAgent(
    name="refund_operator",
    model=MODEL,
    description="Оформлює повернення коштів клієнту",
    instruction=(
        "Ти оформлюєш повернення. Подивись на розмову вище, знайди платіж, "
        "визнаний дублем, і поверни рівно один платіж інструментом refund. "
        "Відповідай українською одним рядком."
    ),
    tools=[refund],
)

escalate_agent = LlmAgent(
    name="escalation_officer",
    model=MODEL,
    description="Ставить тікет у чергу на ручний розгляд людиною",
    instruction=(
        "Ти реєструєш звернення на ручний розгляд. Нічого не повертай — "
        "лише підтвердь клієнту, що тікет передано людині, і назви причину. "
        "Відповідай українською одним рядком."
    ),
)


# ── Маршрутизатор ───────────────────────────────────────────────────────────
# Агента з кроку 1 не чіпаємо: `clone` робить копію з іншим іменем і новими
# полями. Оригінальний `support_agent` потрібен кроку 2 і кроку 3 незміненим.
def build_router(limit: float) -> LlmAgent:
    """Той самий агент підтримки, але з правилом маршруту в інструкції."""
    return support_agent.clone(
        update={
            "name": "support_router",
            "instruction": (
                support_agent.instruction
                + "\n\nПісля висновку передай роботу колезі:\n"
                f"* якщо сума спірного списання не більша за {limit:.2f} USD — "
                "передай оператору повернення;\n"
                f"* якщо більша за {limit:.2f} USD — передай на ручний розгляд.\n"
                "Сам повернення не оформлюй."
            ),
            "sub_agents": [refund_agent, escalate_agent],
        }
    )


async def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--limit",
        type=float,
        default=REFUND_LIMIT_USD,
        help="ліміт повернення без людини; нижче 49.99 маршрут має піти до людини",
    )
    args = parser.parse_args()

    banner(
        "Google ADK",
        "Крок 3b — маршрут обирає модель",
        f"правило написане словами (ліміт {args.limit:.2f} USD), рішення — за LLM",
    )

    metrics = Metrics(framework="ADK", step="Крок 3b — передача управління")
    await run(build_router(args.limit), TICKET, metrics, session_id="g3b")

    metrics.notes = [
        "маршрут обрала модель: порівняйте виклики LLM із кроком 3, де їх нуль на координацію",
        "ціль передачі модель обрала за полем description колеги",
        "правило живе в промпті — відтворюваність не гарантована, спробуйте кілька прогонів",
    ]
    metrics.report()


if __name__ == "__main__":
    asyncio.run(main())
