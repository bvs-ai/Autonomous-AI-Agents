"""Разовий підрахунок векторів у `vectors.json`. На лекції НЕ запускається.

Навіщо кеш: на занятті пошук має відповідати миттєво й однаково при кожному
запуску, без залежності від мережі та чужого провайдера. Тому вектори для
корпусу і для запитів демо рахуються один раз тут і комітяться.

Запуск (потрібна модель ембедингів, див. README):

    ollama pull bge-m3 && python build_vectors.py

Додати новий запит у демо -> дописати рядок у QUERIES і перезапустити.
"""
import json

from corpus import DOCS, EMBED_MODEL, VECTORS_PATH, embed_live, norm
from r4_rerank import EN_DOCS, EN_QUERY
from r5_poisoned_corpus import POISONED

# Усі фіксовані запити демо. Тримаємо списком, щоб було видно, що саме
# закешовано: усе інше піде в мережу.
QUERIES = [
    # r1
    "таймзони",
    "як не починати все спочатку, якщо процес упав посеред задачі",
    "чим запускати тести",
    "чим НЕ запускати тести",
    # r2
    "Як агент не втрачає прогрес після падіння процесу?",
    # r3 — питання і формулювання, які видає rewrite (зібрані прогонами).
    # Сам rewrite породжується моделлю на льоту, тож стовідсоткового попадання
    # в кеш тут бути не може: якщо модель скаже інакше, вектор порахується
    # живцем. Це нормально — r3 і так ходить у мережу по LLM.
    "Як зробити, щоб довга задача переживала перезапуск сервісу?",
    "checkpointer знімок стану перезапуск сервісу",
    "checkpointer збереження стану відновлення після збою процесу",
    "персистентність довгих задач рестарт сервісу",
    "task state persistence service restart",
    # r5
    "Як налаштувати оточення розробки і запускати тести?",
    # r4 — англійський двійник корпусу, під мову reranker'а
    EN_QUERY,
    # ../03_langgraph/ — той самий кеш обслуговує демо на фреймворку: факти, з
    # якими стартує store, і питання сценарію показу (див. langgraph/README.md).
    # Ембедиться там і памʼять, і запит, тому в кеші мають бути обидва.
    "Борис — викладач агентних систем (AI agents).",
    "Борис любить стислі відповіді без води.",
    "таймзонами",
    "Чим запускати тести проєкту?",
    "Як відкотити реліз на проді?",
    "Що ти про мене знаєш?",
    "Запамʼятай: я віддаю перевагу коротким відповідям без емодзі.",
]

# Отруєна нотатка r5 живе поза DOCS, але вектор їй теж потрібен: без нього
# r5 не виконує власної обіцянки працювати без мережі.
TEXTS = [d["text"] for d in DOCS] + [d["text"] for d in EN_DOCS] + [POISONED["text"]] + QUERIES


def main() -> None:
    vectors = {}
    for text in TEXTS:
        key = norm(text)
        if key in vectors:
            continue
        vectors[key] = [round(x, 5) for x in embed_live(text)]
        print(f"  ok  {text[:60]}")
    payload = {
        "model": EMBED_MODEL,
        "dim": len(next(iter(vectors.values()))),
        "note": "Пораховано один раз build_vectors.py. На лекції — тільки читається.",
        "vectors": vectors,
    }
    VECTORS_PATH.write_text(json.dumps(payload, ensure_ascii=False), encoding="utf-8")
    print(f"\n{VECTORS_PATH.name}: {len(vectors)} векторів, dim={payload['dim']}")


if __name__ == "__main__":
    main()
