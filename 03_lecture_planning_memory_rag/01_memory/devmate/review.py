"""Фонове самонавчання: окремий прохід, що вирішує, що варто запам'ятати.

Досі агент зберігав факти лише тоді, коли сам здогадався зробити це посеред
ходу. Це ненадійно з тієї ж причини, з якої людина не веде конспект під час
розмови: у розпал задачі модель зайнята задачею, і пам'ять програє
конкуренцію за увагу.

Тому навчання винесене **після** відповіді користувачу — окремим викликом,
де єдина задача моделі полягає в тому, щоб перечитати діалог і зробити
висновки. Задачі, з якою вона конкурувала б, у цьому виклику просто немає.
"""

from . import llm, memory
from .config import REVIEW_MODEL

# У Hermes лічильник типово 10. Для лекції менше: ревʼю має спрацювати на
# очах у слухачів, а не через півгодини демонстрації.
TURNS_BETWEEN_REVIEWS = 3

# Скільки останніх повідомлень транскрипту показувати ревʼю. Решта відрізана
# навмисно: ревʼю дивиться на свіже, а старе вже або записане, або не варте.
DIGEST_MESSAGES = 12

PROMPT = """\
Ти — фоновий процес самонавчання агента DevMate. Користувач тебе не бачить \
і відповіді від тебе не чекає.

Перечитай уривок діалогу нижче і виріши, чи є в ньому щось, що варто \
пам'ятати в наступних сесіях. Якщо є — збережи через інструмент memory.

ЗБЕРІГАЙ лише стійке: уподобання й виправлення користувача, факти про його \
оточення й проєкт, домовленості, засвоєні уроки.
НЕ ЗБЕРІГАЙ: перебіг цієї задачі, тимчасовий стан, те, що легко з'ясувати \
наново, і те, що вже є в пам'яті нижче.

Нічого вартого немає — так і скажи одним рядком, не викликаючи інструментів. \
Порожня пам'ять краща за засмічену.

Поточна пам'ять:
{snapshot}

Уривок діалогу:
{digest}
"""


def _digest(history: list[dict]) -> str:
    """Транскрипт для ревʼю: останні ходи текстом.

    Дослівні `tool_calls` тут не потрібні — ревʼю цікавить зміст розмови, а
    не механіка викликів. Плаский текст ще й дозволяє пустити ревʼю на іншій
    моделі: чужий prefix cache усе одно не перевикористати, тому економити
    на формі повідомлень нема сенсу.
    """
    lines = []
    for m in history[-DIGEST_MESSAGES:]:
        content = (m.get("content") or "").strip()
        if not content:
            continue
        role = {"user": "Користувач", "assistant": "DevMate", "tool": "Інструмент"}
        lines.append(f"{role.get(m['role'], m['role'])}: {content[:600]}")
    return "\n".join(lines)


def review(history: list[dict], on_tool=None) -> str | None:
    """Один прохід самонавчання. Повертає вердикт моделі або None.

    Помилка ревʼю не повинна валити сесію: користувач свою відповідь уже
    отримав, і збій фонового процесу — не його проблема.
    """
    from . import tools  # тут, а не зверху: tools імпортує memory, буде цикл

    digest = _digest(history)
    if not digest:
        return None

    # Пам'ять показуємо живою, а не замороженим знімком агента: ревʼю має
    # бачити те, що записано хвилину тому, інакше воно продублює запис.
    prompt = PROMPT.format(snapshot=memory.render_all() or "(порожня)", digest=digest)

    try:
        message = llm.chat(
            [{"role": "user", "content": prompt}],
            [s for s in tools.SCHEMAS if s["function"]["name"] == "memory"],
            model=REVIEW_MODEL,
        )
    except Exception as exc:
        return f"ревʼю не вдалося: {exc}"

    if not message.tool_calls:
        return (message.content or "").strip() or None

    # Другий виклик моделі не робимо: результат інструмента нікому читати —
    # ревʼю на цьому й закінчується.
    results = []
    for call in message.tool_calls:
        from .agent import _parse_args

        args = _parse_args(call.function.arguments)
        result = tools.call(call.function.name, args)
        if on_tool:
            on_tool(call.function.name, args, result)
        results.append(result)
    return " | ".join(results)
